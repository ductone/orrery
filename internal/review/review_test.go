func TestParseDiff(t *testing.T) {
	files := ParseDiff([]byte(sampleDiff))
	if len(files) != 5 {
		t.Fatalf("files = %d", len(files))
	}
	for i, want := range []struct {
		path    string
		status  Status
		added   int
		removed int
		binary  bool
	}{
		{"internal/auth/token.go", Modified, 2, 2, false},
		{"docs/guide.md", Added, 2, 0, false},
		{"old.txt", Deleted, 0, 1, false},
		{"b.go", Renamed, 0, 0, false},
		{"logo.png", Modified, 0, 0, true},
	} {
		f := files[i]
		if f.Path != want.path || f.Status != want.status || f.Added != want.added || f.Removed != want.removed || f.Binary != want.binary {
			t.Errorf("file %d = %+v, want %+v", i, f, want)
		}
	}
	if files[3].OldPath != "a.go" {
		t.Errorf("rename source = %q", files[3].OldPath)
	}
	if !strings.HasPrefix(files[0].Patch, "diff --git a/internal/auth/token.go") || strings.Contains(files[0].Patch, "docs/guide.md") {
		t.Errorf("patch boundaries wrong: %q", files[0].Patch)
	}
}

func TestParseDiffHarnessUntrackedFormat(t *testing.T) {
	diff := "\ndiff --git a/new.go b/new.go\nnew file mode 100644\n--- /dev/null\n+++ b/new.go\n@@ new file @@\n+package x\n+func A() {}\n\ndiff --git a/blob.bin b/blob.bin\nnew file mode 100644\n--- /dev/null\n+++ b/blob.bin\n@@ new file @@\n+[binary file omitted]\n"
	files := ParseDiff([]byte(diff))
	if len(files) != 2 || files[0].Status != Added || files[0].Added != 2 || !files[1].Binary {
		t.Fatalf("files = %+v", files)
	}
}

func TestParseDiffMarksTruncation(t *testing.T) {
	files := ParseDiff([]byte("diff --git a/x.go b/x.go\n--- a/x.go\n+++ b/x.go\n@@ -1 +1 @@\n+partial li"))
	if len(files) != 1 || !strings.Contains(files[0].Patch, "[diff truncated]") {
		t.Fatalf("files = %+v", files)
	}
	if ParseDiff(nil) != nil || len(ParseDiff([]byte("not a diff\n"))) != 0 {
		t.Fatal("input without sections yields no files")
	}
}

