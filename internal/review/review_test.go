func TestReviewSizing(t *testing.T) {
	// Turns follow the size of the reviewer's share; risk scores do not move
	// them, since they predicted review outcomes worse than chance.
	calm := Build(context.Background(), []File{file("a/big.go", 55_000)}, "task", &fakeClassifier{}, Options{})
	hot := Build(context.Background(), []File{file("a/big.go", 55_000)}, "task", &fakeClassifier{}, Options{})
	if calm.Turns != baseTurns+55_000/charsPerTurn || hot.Turns != calm.Turns {
		t.Fatalf("turns calm=%d hot=%d", calm.Turns, hot.Turns)
	}
	// A patch larger than a shard is truncated, so turns follow the shard size.
	if capped := Build(context.Background(), []File{file("a/huge.go", 400_000)}, "task", nil, Options{}); capped.Turns != baseTurns+defaultShardChars/charsPerTurn || capped.Turns > maxTurns {
		t.Fatalf("turns = %d", capped.Turns)
	}
}

func TestPackGroupsDirectoriesAndShards(t *testing.T) {
	files := []File{file("api/a.go", 30_000), file("api/b.go", 20_000), file("web/c.ts", 30_000), file("web/d.ts", 20_000), file("cmd/e.go", 5_000)}
	plan := Build(context.Background(), files, "task", nil, Options{ShardChars: 60_000})
	// Directories stay together; a small directory joins a shard with room.
	if len(plan.Shards) != 2 || paths(plan.Shards[0]) != "api/a.go,api/b.go" || paths(plan.Shards[1]) != "web/c.ts,web/d.ts,cmd/e.go" {
		t.Fatalf("shards = %d: %s | %s", len(plan.Shards), paths(plan.Shards[0]), paths(plan.Shards[len(plan.Shards)-1]))
	}
	spec := plan.Spec(1)
	if !strings.Contains(spec, "part 2 of 2") || strings.Contains(spec, "diff --git a/api/a.go") || !strings.Contains(spec, "diff --git a/web/c.ts") {
		t.Fatalf("shard spec wrong")
	}
}

func paths(s Shard) string {
	var out []string
	for _, f := range s.Files {
		out = append(out, f.Path)
	}
	return strings.Join(out, ",")
}

