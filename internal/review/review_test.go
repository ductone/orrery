func TestMerge(t *testing.T) {
	single := Plan{Shards: []Shard{{}}}
	if out := Merge(single, []Verdict{{Conclusive: true, Pass: true}}); !out.Pass || out.Inconclusive {
		t.Fatalf("out = %+v", out)
	}
	if out := Merge(single, []Verdict{{Conclusive: true, Findings: []string{"nil deref"}}}); out.Pass || out.Findings[0] != "nil deref" {
		t.Fatalf("out = %+v", out)
	}
	multi := Plan{Shards: []Shard{{}, {}, {}}}
	out := Merge(multi, []Verdict{{Shard: 0, Conclusive: true, Pass: true}, {Shard: 1, Conclusive: true, Findings: []string{"race"}}, {Shard: 2, Accepted: "part 3 accepted"}})
	if out.Pass || out.Inconclusive || out.Findings[0] != "[part 2] race" || out.Notes[0] != "part 3 accepted" {
		t.Fatalf("out = %+v", out)
	}
	if out := Merge(multi, []Verdict{{Shard: 0, Conclusive: true, Pass: true}, {Shard: 1}}); out.Pass || !out.Inconclusive {
		t.Fatalf("a shard without a verdict makes the review inconclusive: %+v", out)
	}
}

func TestJevClassifierAsksOneQuestionPerItem(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls.Add(1)
		var req struct {
			State     map[string]any             `json:"state"`
			Questions map[string]json.RawMessage `json:"questions"`
		}
		_ = json.NewDecoder(r.Body).Decode(&req)
		answers := map[string]any{}
		for name := range req.Questions {
			p := 0.2
			if req.State["file"] == "ci.yaml" || strings.Contains(fmt.Sprint(req.State["finding"]), "race") {
				p = 0.9
			}
			answers[name] = map[string]any{"type": "noul", "noul": p}
			if name == "risk" {
				answers[name] = map[string]any{"type": "score", "score": 1.0, "legend": map[string]string{"0": "l", "1": "m", "2": "h"}}
			}
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"model": "jev-1.13.0", "answers": answers})
	}))
	defer srv.Close()
	c := JevClassifier{Client: jev.New("k", srv.URL, "", time.Second)}
	ctx := context.Background()
	scores, err := c.NeedsReview(ctx, "task", []File{{Path: "README.md"}, {Path: "ci.yaml"}})
	if err != nil || scores[0] != 0.2 || scores[1] != 0.9 {
		t.Fatalf("needs review = %v %v", scores, err)
	}
	if calls.Load() != 2 {
		t.Fatalf("calls = %d, want one per item", calls.Load())
	}
}

func TestJevClassifierFailsTheWholeBatch(t *testing.T) {
	var n atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		if n.Add(1) == 2 {
			w.WriteHeader(529)
			return
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"answers": map[string]any{"needs_review": map[string]any{"type": "noul", "noul": 0.5}}})
	}))
	defer srv.Close()
	c := JevClassifier{Client: jev.New("k", srv.URL, "", time.Second)}
	if _, err := c.NeedsReview(context.Background(), "t", []File{{Path: "a"}, {Path: "b"}, {Path: "c"}}); err == nil {
		t.Fatal("one failed call must fail the batch rather than score the file zero")
	}
}

func TestCascadeSizeAndTestRules(t *testing.T) {
	small := []File{{Path: "a.go", Added: 10, Removed: 2, Class: Code}, {Path: "go.sum", Added: 900, Class: Lockfile}}
	if Large(small) {
		t.Fatal("lockfile churn must not make a change large")
	}
	if !Large([]File{{Path: "a.go", Added: CascadeMaxLines + 1, Class: Code}}) {
		t.Fatal("a change over the line limit is large")
	}
	cases := map[string]bool{
		"pkg/a_test.go":         true,
		"tests/test_api.py":     true,
		"web/app.spec.ts":       true,
		"pkg/a.go":              false,
		"docs/testing-guide.md": false,
	}
	for p, want := range cases {
		if got := TouchesTests([]File{{Path: p, Removed: 1}}); got != want {
			t.Errorf("%s: got %v, want %v", p, got, want)
		}
	}
	if TouchesTests([]File{{Path: "pkg/a_test.go", Added: 5}}) {
		t.Fatal("only adding tests does not need a reviewer's judgement")
	}
}
